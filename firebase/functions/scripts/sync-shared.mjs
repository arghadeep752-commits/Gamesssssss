// Copies the platform-neutral shared sources into src/shared so they compile into
// the deployed bundle (Cloud Build installs from npm and cannot see the monorepo).
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, '..', '..', '..', 'packages', 'shared', 'src');
const target = join(here, '..', 'src', 'shared');

if (!existsSync(source)) {
  if (existsSync(target)) {
    console.log('sync-shared: monorepo sources not found, using existing src/shared');
    process.exit(0);
  }
  console.error(`sync-shared: cannot find ${source}`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
const files = readdirSync(source).filter((f) => f.endsWith('.ts'));
for (const file of files) cpSync(join(source, file), join(target, file));
writeFileSync(
  join(target, 'README.md'),
  'Generated by scripts/sync-shared.mjs from packages/shared/src. Do not edit here.\n',
);
console.log(`sync-shared: copied ${files.length} files`);
