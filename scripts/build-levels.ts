/**
 * Offline level builder. Run with:  npm run levels:build
 *
 * For every level slot it generates many seeded candidate layouts, rejects any
 * that fail validation, and keeps the one closest to the design curve in
 * src/levels/tierParams.ts. The result is written as compact data to
 * src/levels/data/packedLevels.ts, so the app never generates levels at runtime.
 * Output is deterministic: the same code always produces the same levels.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { prepareLevel } from '../src/game/board';
import { generateLayout } from '../src/game/generator';
import { packLevel, unpackLevel } from '../src/game/geometry';
import { createRng, hashString } from '../src/game/rng';
import { measure, type LevelMetrics } from '../src/game/solver';
import type { PackedLevel } from '../src/game/types';
import { validateLevel } from '../src/game/validate';
import { HANDMADE_LEVELS } from '../src/levels/handmade';
import { designCost, designTarget, tierForLevel, tierProgress } from '../src/levels/tierParams';

const LEVEL_COUNT = 100;
const CANDIDATES = 90;
const OUT = join(__dirname, '..', 'src', 'levels', 'data', 'packedLevels.ts');


const levels: PackedLevel[] = [];
const seen = new Set<string>();
const report: string[] = [];

for (let n = 1; n <= LEVEL_COUNT; n++) {
  const tier = tierForLevel(n);
  let chosen: PackedLevel | null = null;
  let chosenMetrics: LevelMetrics | null = null;
  if (n <= HANDMADE_LEVELS.length) {
    chosen = HANDMADE_LEVELS[n - 1];
    const level = unpackLevel(chosen, { id: 'tmp', number: n, tier });
    const errors = validateLevel(level);
    if (errors.length) throw new Error(`Handmade level ${n} is invalid:\n${errors.join('\n')}`);
    chosenMetrics = measure(prepareLevel(level));
  } else {
    const target = designTarget(tier, tierProgress(n));
    let bestCost = Infinity;
    for (let k = 0; k < CANDIDATES; k++) {
      const rng = createRng(hashString(`arrow-flow:level:${n}:${k}`));
      const arrows = generateLayout(target.options, rng);
      const level = { id: 'tmp', number: n, tier, width: target.options.width, height: target.options.height, arrows };
      if (validateLevel(level).length) continue;
      const packed = packLevel(level.width, level.height, arrows);
      const key = `${packed.w}x${packed.h}:${packed.a}`;
      if (seen.has(key)) continue;
      const m = measure(prepareLevel(level));
      const c = designCost(m, target);
      if (c < bestCost) {
        bestCost = c;
        chosen = packed;
        chosenMetrics = m;
      }
    }
  }
  if (!chosen || !chosenMetrics) throw new Error(`Could not build level ${n}`);
  seen.add(`${chosen.w}x${chosen.h}:${chosen.a}`);
  levels.push(chosen);
  const m = chosenMetrics;
  report.push(
    `${String(n).padStart(3)} ${tier.padEnd(8)} ${chosen.w}x${chosen.h}  arrows ${String(m.arrows).padStart(2)}  ` +
      `free ${String(m.initialFree).padStart(2)}  depth ${String(m.rounds).padStart(2)}  ` +
      `bent ${String(m.bentArrows).padStart(2)}  fill ${m.fill.toFixed(2)}`,
  );
}

const body = levels.map((l) => `  { w: ${l.w}, h: ${l.h}, a: '${l.a}' },`).join('\n');
const file = `// AUTO-GENERATED by scripts/build-levels.ts. Do not edit by hand; run \`npm run levels:build\`.
// ${levels.length} levels. Token format: see decodeArrow in src/game/geometry.ts.
import type { PackedLevel } from '../../game/types';

export const PACKED_LEVELS: readonly PackedLevel[] = [
${body}
];
`;
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, file);
console.log(report.join('\n'));
console.log(`\nWrote ${levels.length} levels to ${OUT}`);
