/**
 * Builds src/game/levelPack.ts: levels 1..COUNT, each the hardest of several
 * seeded candidates, validated before it is written. Deterministic.
 * Run: npx tsx scripts/build-levels.ts
 */
import { writeFileSync } from 'node:fs';
import { validateLevel } from '../src/game/engine';
import { levelStats } from '../src/game/generator';
import { buildLevel, encodeLevel, decodeLevel, levelSpec } from '../src/game/levels';

const COUNT = 300;
const TRIES = 6;
const out: string[] = [];
let arrows = 0;
let maxArrows = 0;
let free = 0;
let depth = 0;
for (let n = 1; n <= COUNT; n++) {
  const info = buildLevel(n, TRIES);
  const errs = validateLevel(info.level);
  if (errs.length) throw new Error(`level ${n}: ${errs.join(', ')}`);
  const text = encodeLevel(info);
  const back = decodeLevel(text);
  if (JSON.stringify(back.level.arrows) !== JSON.stringify(info.level.arrows)) throw new Error(`level ${n}: encoding mismatch`);
  if (back.level.w !== levelSpec(n).params.w || back.level.h !== levelSpec(n).params.h) throw new Error(`level ${n}: size`);
  const st = levelStats(info.level);
  arrows += st.arrows;
  maxArrows = Math.max(maxArrows, st.arrows);
  free += st.freeShare;
  depth += st.depth;
  out.push(text);
}
const body = out.map((s) => `  '${s}',`).join('\n');
writeFileSync(
  new URL('../src/game/levelPack.ts', import.meta.url),
  `// Generated by scripts/build-levels.ts. Do not edit by hand.\n// ${COUNT} levels, each the hardest of ${TRIES} candidates.\nexport const LEVEL_PACK: readonly string[] = [\n${body}\n];\n`,
);
console.log(`levels=${COUNT} avgArrows=${(arrows / COUNT).toFixed(1)} maxArrows=${maxArrows} avgFree=${(free / COUNT).toFixed(2)} avgDepth=${(depth / COUNT).toFixed(1)} bytes=${out.join('').length}`);
