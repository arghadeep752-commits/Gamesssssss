#!/usr/bin/env bash
# Publishes one build job's evidence to the `devdarshan-ci` branch, under
# runs/<run-number>-<attempt>/<app>/: the APK verification report, checksums, the
# emulator smoke-test results and screenshots, and trimmed logs. Viewable on GitHub
# from a phone without downloading artifacts. Never fails the build.
#
#   publish-diagnostics.sh <user|admin>      (needs GH_TOKEN with contents: write)
set -uo pipefail
APP="${1:?app}"
SRC="$GITHUB_WORKSPACE/build-output/$APP"
[ -d "$SRC" ] || { echo "nothing to publish"; exit 0; }
BRANCH="devdarshan-ci"
RUN_DIR="runs/${GITHUB_RUN_NUMBER}-${GITHUB_RUN_ATTEMPT:-1}"
DEST="$RUN_DIR/$APP"
WORK="${RUNNER_TEMP:-/tmp}/devdarshan-ci-branch"
REMOTE="https://x-access-token:${GH_TOKEN}@github.com/${GITHUB_REPOSITORY}.git"
rm -rf "$WORK"

if git ls-remote --exit-code --heads "$REMOTE" "$BRANCH" >/dev/null 2>&1; then
  git clone --quiet --depth 1 --branch "$BRANCH" "$REMOTE" "$WORK" || exit 0
else
  mkdir -p "$WORK" && git -C "$WORK" init --quiet -b "$BRANCH" && git -C "$WORK" remote add origin "$REMOTE"
  printf '# DevDarshan CI evidence\n\nOne folder per build run: APK verification reports, emulator smoke-test results and screenshots, and trimmed logs. Generated by `.github/workflows/android.yml`.\n' > "$WORK/README.md"
fi
git -C "$WORK" config user.name "github-actions[bot]"
git -C "$WORK" config user.email "41898282+github-actions[bot]@users.noreply.github.com"

mkdir -p "$WORK/$DEST"
for f in report.md SHA256SUMS.txt; do [ -f "$SRC/$f" ] && cp "$SRC/$f" "$WORK/$DEST/"; done
for log in "$SRC"/*.log; do [ -f "$log" ] && tail -n 4000 "$log" > "$WORK/$DEST/$(basename "$log")"; done
if [ -d "$SRC/smoke-test" ]; then
  mkdir -p "$WORK/$DEST/smoke-test"
  find "$SRC/smoke-test" -maxdepth 1 -type f \( -name '*.md' -o -name '*.png' -o -name '*.xml' -o -name '*.txt' \) \
    ! -name 'logcat.txt' -exec cp {} "$WORK/$DEST/smoke-test/" \;
  if [ -f "$SRC/smoke-test/logcat.txt" ]; then
    grep -E 'ReactNative|ReactNativeJS|AndroidRuntime|FATAL|DevDarshan|devdarshan|Expo|Hermes|WallpaperManager' \
      "$SRC/smoke-test/logcat.txt" | tail -n 3000 > "$WORK/$DEST/smoke-test/logcat-filtered.txt" || true
  fi
fi
{
  echo "- commit: ${GITHUB_SHA:0:7}"
  echo "- workflow run: https://github.com/${GITHUB_REPOSITORY}/actions/runs/${GITHUB_RUN_ID}"
  echo "- job status: ${JOB_STATUS:-unknown}"
} > "$WORK/$DEST/run.md"

git -C "$WORK" add -A
git -C "$WORK" commit --quiet -m "CI evidence: $APP, run ${GITHUB_RUN_NUMBER}" || exit 0
for attempt in 1 2 3 4 5; do
  if git -C "$WORK" push --quiet origin "HEAD:$BRANCH" 2>/dev/null; then
    echo "Published to $BRANCH/$DEST"
    echo "Evidence: https://github.com/${GITHUB_REPOSITORY}/tree/$BRANCH/$DEST" >> "${GITHUB_STEP_SUMMARY:-/dev/null}"
    exit 0
  fi
  sleep $((attempt * 3))
  git -C "$WORK" pull --quiet --rebase origin "$BRANCH" 2>/dev/null || true
done
echo "::warning::Could not publish CI evidence to $BRANCH"
exit 0
